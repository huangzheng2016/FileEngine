// Generates src/api/idl.gen.ts from ../idl. The IDL is the source of truth for the wire contract.
//
//   node scripts/idl-types.ts          (npm run gen:idl)
//
// Rules: `code` and `msg` are the envelope and never part of a payload type; an i64 whose go.tag says
// `,string` is a string on the wire (an Id), every other number stays a number; `optional` becomes `?`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format } from 'prettier'

export interface IdlField {
  id: number
  name: string
  type: string
  optional: boolean
  doc: string[]
  stringId: boolean
}

export interface IdlStruct {
  name: string
  file: string
  doc: string[]
  fields: IdlField[]
}

export interface IdlRoute {
  method: 'GET' | 'POST'
  path: string
  name: string
  req: string
  resp: string
}

const ENVELOPE = new Set(['code', 'msg'])

export function parseStructs(file: string, source: string): IdlStruct[] {
  const out: IdlStruct[] = []
  let doc: string[] = []
  let current: IdlStruct | null = null
  for (const raw of source.split('\n')) {
    const line = raw.trim()
    if (line.startsWith('//')) {
      doc.push(line.replace(/^\/\/\s?/, ''))
      continue
    }
    if (current === null) {
      const m = /^struct\s+(\w+)\s*\{(\s*\})?$/.exec(line)
      if (m) {
        current = { name: m[1], file, doc, fields: [] }
        if (m[2]) {
          out.push(current)
          current = null
        }
      }
      doc = []
      continue
    }
    if (line === '}') {
      out.push(current)
      current = null
      doc = []
      continue
    }
    const f = /^(\d+):\s+(optional\s+)?(list<[\w.]+>|[\w.]+)\s+(\w+)\s*(\(.*\))?\s*,?$/.exec(line)
    if (!f) {
      if (line) throw new Error(`${file}: cannot parse field line: ${line}`)
      continue
    }
    current.fields.push({
      id: Number(f[1]),
      name: f[4],
      type: f[3],
      optional: !!f[2],
      doc,
      stringId: /,string"/.test(f[5] ?? ''),
    })
    doc = []
  }
  if (current) throw new Error(`${file}: unterminated struct ${current.name}`)
  return out
}

export function parseRoutes(source: string): IdlRoute[] {
  const out: IdlRoute[] = []
  const re = /^\s*([\w.]+)\s+(\w+)\(1:\s*([\w.]+)\s+req\)\s*\(api\.(get|post)="([^"]+)"\)/gm
  for (const m of source.matchAll(re)) {
    out.push({
      resp: m[1].split('.').pop()!,
      name: m[2],
      req: m[3].split('.').pop()!,
      method: m[4].toUpperCase() as 'GET' | 'POST',
      path: m[5],
    })
  }
  return out
}

export function loadIdl(idlDir: string) {
  const structs: IdlStruct[] = []
  const apiDir = join(idlDir, 'api')
  for (const f of readdirSync(apiDir).sort()) {
    if (f.endsWith('.thrift')) structs.push(...parseStructs(f, readFileSync(join(apiDir, f), 'utf8')))
  }
  const names = new Set<string>()
  for (const s of structs) {
    if (names.has(s.name)) throw new Error(`duplicate struct name ${s.name}; the generated module has one namespace`)
    names.add(s.name)
  }
  const routes = parseRoutes(readFileSync(join(idlDir, 'api.thrift'), 'utf8'))
  return { structs, routes }
}

function tsType(f: IdlField): string {
  const base = (t: string): string => {
    const list = /^list<([\w.]+)>$/.exec(t)
    if (list) return `${base(list[1])}[]`
    switch (t) {
      case 'i32':
      case 'double':
        return 'number'
      case 'i64':
        return f.stringId ? 'Id' : 'number'
      case 'bool':
        return 'boolean'
      case 'string':
        return 'string'
      default:
        return t.split('.').pop()!
    }
  }
  return base(f.type)
}

export async function generate(idlDir: string): Promise<string> {
  const { structs } = loadIdl(idlDir)
  const lines = [
    '// Code generated by scripts/idl-types.ts from the IDL. DO NOT EDIT.',
    '',
    '// An int64 id: a decimal string on the wire; "0" means none.',
    'export type Id = string',
    '',
  ]
  for (const s of structs) {
    const fields = s.fields.filter((f) => !ENVELOPE.has(f.name))
    if (!fields.length) {
      lines.push(`export type ${s.name} = Record<string, never>`, '')
      continue
    }
    for (const d of s.doc) lines.push(`// ${d}`)
    lines.push(`export interface ${s.name} {`)
    for (const f of fields) {
      for (const d of f.doc) lines.push(`  // ${d}`)
      lines.push(`  ${f.name}${f.optional ? '?' : ''}: ${tsType(f)}`)
    }
    lines.push('}', '')
  }
  return format(lines.join('\n'), { parser: 'typescript', semi: false, singleQuote: true, printWidth: 120 })
}

const root = fileURLToPath(new URL('..', import.meta.url))
export const IDL_DIR = join(root, '..', 'idl')
export const OUT_FILE = join(root, 'src', 'api', 'idl.gen.ts')

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT_FILE, await generate(IDL_DIR))
}
